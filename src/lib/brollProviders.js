/**
 * B-roll source registry — the provider-agnostic catalogue behind the picker.
 *
 * Every source is described by data, never by code branches in the UI. Adding a
 * provider means adding one entry here (plus, if it needs a key, one adapter in
 * the `stock-search` edge function). The UI reads this list to decide what to
 * show, what to enable, and what licence text to display.
 *
 * Why the re-host policy matters
 * ------------------------------
 * Directorr composites assets on a <canvas> and pipes it to MediaRecorder, so
 * an asset MUST be same-origin or served with `Access-Control-Allow-Origin`.
 * That makes "store a copy in the ephemeral bucket" the only universally safe
 * strategy — and it happens to be what the licences ask for:
 *
 *   allowed     — re-hosting is permitted (Pexels). We store a copy anyway.
 *   required    — hotlinking is forbidden, a copy is mandatory (Pixabay).
 *   prohibited  — a copy is forbidden and hotlinking taints the canvas
 *                 (Unsplash), so the source cannot be offered at all.
 *
 * See docs/SETUP-BROLL.md for the key-handling story.
 */

