export const sourceById = (id) => SOURCES.find((source) => source.id === id) || null;

/** Stock hosts -> source id, so a pasted link gets the right licence text. */
const HOST_MAP = [
  [/(^|\.)pexels\.com$/i, 'pexels'],
  [/(^|\.)pixabay\.com$/i, 'pixabay'],
  [/(^|\.)unsplash\.com$/i, 'unsplash'],
];

export function sourceForUrl(url) {
  try {
    const { hostname } = new URL(url);
    const match = HOST_MAP.find(([pattern]) => pattern.test(hostname));
    return match ? sourceById(match[1]) : null;
  } catch {
    return null;
  }
}

/** Sources that need a key-holding endpoint before they can be searched. */
export function keyedSources() {
  return SOURCES.filter((source) => source.searchable);
}
